"""Time-warp the early recovery only; probe first, then bounded R76 training.

R74 wait-pose offsets leave ten training failures already side-on at wait
end. Test four early-motion duration factors while freezing the joint target
path, home wait, pulse, terminal commands, feedback and physical gates.
References are regenerated by physical simulation. No mid-trial reset.
"""
import argparse
from concurrent.futures import ProcessPoolExecutor
import json
from pathlib import Path
import time
import numpy as np

from diagnostics import train_getup_wait_pose_r74 as base
from diagnostics.getup_independent_native import DT, digest
from diagnostics.probe_getup_terminal_timing_r72 import timed_targets
from diagnostics.search_getup_reference_feedback_r64 import record_reference, rollout
from diagnostics.train_getup_prefix_pose_r73 import success


def warped_prefix(ck, factors):
    factors = np.asarray(factors, dtype=float)
    if factors.shape != (4,) or not np.isfinite(factors).all():
        raise ValueError('Need four finite duration factors')
    if (factors < .7 - 1e-10).any() or (factors > 1.3 + 1e-10).any():
        raise ValueError('Duration factor outside bounded search')
    ix = np.flatnonzero(ck['prefix_phases'] == 0)
    if len(ix) < 8 or not np.array_equal(ix, np.arange(len(ix))):
        raise ValueError('Recovery must be a contiguous initial phase')
    original = ck['prefix_targets'][ix]
    chunks = []
    for part, factor in zip(np.array_split(original, 4), factors):
        n = max(2, round(len(part) * factor))
        if n == len(part):
            chunks.append(part.copy())
        else:
            at = np.linspace(0., len(part) - 1, n)
            chunks.append(np.stack([np.interp(at, np.arange(len(part)), part[:, j])
                                    for j in range(part.shape[1])], axis=1))
    early = np.concatenate(chunks)
    prefix = np.concatenate([early, ck['prefix_targets'][len(ix):]])
    phases = np.r_[np.zeros(len(early), dtype=ck['prefix_phases'].dtype),
                   ck['prefix_phases'][len(ix):]]
    return {**ck, 'prefix_targets': prefix, 'prefix_phases': phases}


def run_path(factors, hold):
    sim, cases, ck, ids = base._CTX
    changed = warped_prefix(ck, factors)
    targets, phases = timed_targets(sim, changed, (.4, .6, .8), hold)
    source, peaks, _, _ = cases[None]
    ref = record_reference(sim, source, peaks, True, targets)
    gains = np.concatenate([ck['prefix_gains'], ck['terminal_gains']])
    return targets, phases, ref, gains


def objective(factors):
    sim, cases, ck, ids = base._CTX
    try:
        targets, phases, ref, gains = run_path(factors, 2.)
    except RuntimeError:
        return {'objective': -10000., 'successes': 0, 'nominal_success': False}
    nominal, _ = rollout(sim, *cases[None][:2], True, targets, phases, ids, ref, gains)
    if not success(nominal, len(targets), 1.):
        return {'objective': -1000. + nominal['score'], 'successes': 0,
                'nominal_success': False, 'nominal': nominal}
    rows = [rollout(sim, *case[:2], True, targets, phases, ids, ref, gains)[0]
            for seed, case in cases.items() if seed is not None]
    passed = sum(success(r, len(targets), 1.) for r in rows)
    scores = np.sort([r['score'] for r in rows])
    value = float(scores[:6].mean() + .2 * scores.mean() + 14 * passed
                  - .1 * np.dot(factors - 1., factors - 1.))
    return {'objective': value, 'successes': passed, 'nominal_success': True,
            'nominal': nominal, 'cases': rows}


def qualify(job):
    seed, factors, directory = job
    sim, cases, ck, ids = base._CTX
    source, peaks, initial, initial_hash = cases[seed]
    row = {'seed': seed, 'initial_fallen': True, 'initial': initial,
           'initial_state_sha256': initial_hash}
    for name, params in [('baseline', np.ones(4)), ('candidate', factors)]:
        targets, phases, ref, gains = run_path(params, 35.)
        value, trace = rollout(sim, source, peaks, True, targets, phases, ids,
                               ref, gains, True)
        value['success'] = success(value, len(targets), 30.)
        row[name] = value
        np.savez_compressed(Path(directory) / f'{name}_{seed}.npz',
                            time=[r[0] for r in trace], qpos=[r[1] for r in trace],
                            qvel=[r[2] for r in trace], phase=[r[3] for r in trace],
                            strict=[r[4] for r in trace], margin_m=[r[5] for r in trace],
                            imu_error=[r[6] for r in trace], residual_rad=[r[7] for r in trace])
    return row


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--workers', type=int, default=6)
    p.add_argument('--train', action='store_true')
    p.add_argument('--initial', type=Path)
    p.add_argument('--generations', type=int, default=32)
    p.add_argument('--population', type=int, default=24)
    p.add_argument('--seed', type=int, default=176)
    args = p.parse_args()
    if args.output.exists() or args.workers < 1 or args.generations < 1 or args.population < 12:
        p.error('Need fresh output and bounded positive search settings')
    root = Path('/data/shijinsheng/open_duck')
    scene = root / 'training/getup_decomposed_r4/model/scene.xml'
    stand = root / 'projects/Open_Duck_Mini/BEST_WALK_ONNX_2.onnx'
    with np.load(args.checkpoint, allow_pickle=False) as z:
        ck = {k: z[k] for k in z.files}
    if 'best_wait_delta' in ck:
        p.error('Use frozen pre-R74 baseline; do not combine wait and timing interventions')
    train = list(range(769000, 769008)) + list(range(773000, 773016))
    heldout = list(range(778000, 778040))
    assert not set(train) & set(heldout)
    args.output.mkdir(parents=True)
    contract = {'simulation_only': True, 'hardware_readiness': False,
                'full_task_completed': False, 'no_midpath_state_reset': True,
                'method': 'four-quarter initial-motion timing CEM' if args.train else 'early timing ablation',
                'training_only': not args.train, 'pose': 'left_side',
                'hypothesis': 'early contact timing reaches unstable wait entry',
                'training_seeds': train, 'heldout_seeds': heldout if args.train else [],
                'factor_bounds': [.7, 1.3], 'control_dt_s': DT,
                'frozen': ['spatial_joint_target_path', 'home_wait_targets_and_duration',
                           'pulse_and_terminal_commands', 'feedback_gains', 'physics', 'motor_limits', 'strict_gate'],
                'required_strict_seconds': 30., 'hold_seconds': 35.,
                'source_sha256': digest(__file__), 'scene_sha256': digest(scene),
                'stand_sha256': digest(stand), 'checkpoint_sha256': digest(args.checkpoint),
                'dependency_hashes': {name: digest(Path(__file__).parent / name) for name in
                    ['train_getup_wait_pose_r74.py', 'probe_getup_terminal_timing_r72.py',
                     'search_getup_reference_feedback_r64.py', 'validate_getup_fullpath_r27.py',
                     'train_getup_fullpath_r27.py', 'getup_independent_native.py']},
                'seed': args.seed, 'generation_budget': args.generations if args.train else 0,
                'population': args.population if args.train else 0, 'workers': args.workers}
    if args.initial: contract['initial_sha256'] = digest(args.initial)
    (args.output / 'contract.json').write_text(json.dumps(contract, indent=2))
    with ProcessPoolExecutor(max_workers=args.workers, initializer=base.init_worker,
                             initargs=(str(scene), str(stand), ck, train)) as pool:
        if not args.train:
            grid = [np.ones(4)] + [np.full(4, s) for s in [.7, .8, .9, 1.1, 1.2, 1.3]]
            for j in range(4):
                for s in [.8, 1.2]:
                    factors = np.ones(4); factors[j] = s; grid.append(factors)
            rows = []
            for factors, result in zip(grid, pool.map(objective, grid)):
                rows.append({'factors': factors.tolist(), **result})
                print('TIMING', factors.tolist(), 'NOMINAL', result['nominal_success'],
                      'TRAIN', result['successes'], '/24', flush=True)
            eligible = [r for r in rows if r['nominal_success']]
            if not eligible: raise RuntimeError('Even frozen nominal baseline failed')
            best = max(eligible, key=lambda r: r['objective'])
            np.savez_compressed(args.output / 'selected.npz', factors=best['factors'])
            (args.output / 'results.json').write_text(json.dumps(
                {**contract, 'baseline': rows[0], 'selected': best, 'results': rows}, indent=2))
            print('PROBE_COMPLETE', best['successes'], '/24', flush=True)
            return
        rng = np.random.default_rng(args.seed)
        mean, std = np.ones(4), np.full(4, .06)
        if args.initial:
            with np.load(args.initial, allow_pickle=False) as z: mean = z['factors'].copy()
        history, best, stale = [], None, 0
        start = time.monotonic()
        for gen in range(args.generations):
            population = [np.ones(4), mean.copy()]
            if best is not None: population.append(best[0].copy())
            while len(population) < args.population:
                center = best[0] if best and len(population) % 3 == 0 else mean
                population.append(np.clip(center + rng.normal(0., std), .7, 1.3))
            ranked = sorted(zip(population, pool.map(objective, population)),
                            key=lambda r: -r[1]['objective'])
            if best is None or ranked[0][1]['objective'] > best[1]['objective'] + 1e-8:
                best, stale = ranked[0], 0
            else: stale += 1
            elite = np.array([r[0] for r in ranked[:max(4, args.population // 5)]])
            mean = .5 * mean + .5 * elite.mean(axis=0)
            std = np.maximum(.015, .7 * std + .3 * elite.std(axis=0))
            history.append({'generation': gen + 1, 'best': best[1], 'stale': stale,
                            'wall_seconds': time.monotonic() - start})
            np.savez_compressed(args.output / 'checkpoint.npz', **ck,
                                best_time_factors=best[0], time_mean=mean, time_std=std)
            (args.output / 'search_history.json').write_text(json.dumps(history, indent=2))
            print('GEN', gen + 1, 'TRAIN', best[1]['successes'], '/24', 'NOMINAL',
                  best[1]['nominal_success'], 'STALE', stale, flush=True)
            if best[1]['successes'] == len(train) or stale >= 12: break
    with ProcessPoolExecutor(max_workers=args.workers, initializer=base.init_worker,
                             initargs=(str(scene), str(stand), ck, heldout)) as pool:
        rows = list(pool.map(qualify, [(s, best[0], str(args.output))
                                      for s in [None] + heldout], chunksize=1))
    rs = rows[1:]
    report = {**contract, 'training_best': best[1], 'generations_completed': len(history),
              'canonical': rows[0], 'heldout': rs, 'heldout_trials': len(rs),
              'baseline_successes': sum(r['baseline']['success'] for r in rs),
              'heldout_successes': sum(r['candidate']['success'] for r in rs)}
    (args.output / 'results.json').write_text(json.dumps(report, indent=2))
    print('HELDOUT', report['heldout_successes'], '/40 BASELINE', report['baseline_successes'], flush=True)
    print('RESULTS_SAVED', args.output, flush=True)


if __name__ == '__main__': main()
